#!/usr/bin/env python3
"""Build the VxThinking knowledge / customer-service training corpus.

Turns the *live* docs into training data under ``app/data/datasets/supportllm/`` so
the specialist can be (re)trained on real VxCloud (DevOps) and SalesShift
(customer-service) knowledge — "train again, and again":

    python -m app.services.docs.build                 # refresh the retrieval index first
    python scripts/ml/build_knowledge_dataset.py       # regenerate the corpus from it
    python -m app.services.ai.ml.train ...             # retrain on the corpus

Outputs (all consumed by the trainer — .md/.txt/.json):
  vxcloud_llms.md / salesshift_llms.md   curated llms.txt, verbatim (highest quality)
  vxcloud_knowledge.md / salesshift_knowledge.md   every indexed section, with its source URL
  vxnode_runbook.md                      the vxnode DevOps runbook (ops knowledge)
  customer_service_faq.json              common CS questions -> grounded answers + source

Nothing here is invented: the .md knowledge is the retrieval index serialised, and the
FAQ answers are produced by the same extractive answerer the API serves, so they can
never contain a command that is not in the docs.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from urllib.parse import urlparse

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))

from app.services.docs import DocIndex, answer                     # noqa: E402
from app.services.docs.service import default_index_path           # noqa: E402

OUT_DIR = REPO / "app" / "data" / "datasets" / "supportllm"
VXNODE_README = REPO.parent / "vxnode" / "README.md"

VXCLOUD_LLMS = "https://vxcloud.io/docs/llms.txt"
SALESSHIFT_LLMS = "https://salesshift.vxcloud.io/docs/llms.txt"

# Common customer-service / DevOps questions. Answers are generated by the live
# extractive answerer against the index, so they stay grounded and in sync.
FAQ_QUESTIONS = [
    # --- SalesShift: billing / plans / trial (highest-volume CS) ---
    "How much does SalesShift cost?",
    "What are the SalesShift plans and prices?",
    "What is the cheapest SalesShift plan?",
    "How do I start the SalesShift free trial?",
    "What happens when my SalesShift trial expires?",
    "What are SalesShift AI credits?",
    "How many emails can I send on the SalesShift free trial?",
    "Can I use my own mailbox with SalesShift?",
    "Can I bring my own model key to SalesShift?",
    "How does SalesShift metered usage billing work?",
    # --- SalesShift: product how-to ---
    "How do I authenticate to the SalesShift API?",
    "How do I log in with the SalesShift CLI?",
    "What is the SalesShift API base path?",
    "How do I send a tracked email with SalesShift?",
    "How do I create a sequence in SalesShift?",
    "How do I reveal a prospect in SalesShift?",
    "How do I create a contract in SalesShift?",
    "How do I create a quote or invoice in SalesShift?",
    "How do I improve email deliverability in SalesShift?",
    "How do I set up a webhook in SalesShift?",
    # --- VxCloud: DevOps / platform ---
    "How do I install vxcli?",
    "How do I log in with vxcli?",
    "How do I authenticate to the REST API?",
    "How do I provision a VM with vxcli?",
    "How do I deploy a FastAPI app with vxcli?",
    "How do I deploy a Next.js app?",
    "How do I store secrets in Vault?",
    "How do I set up a blue-green CI/CD pipeline?",
    "Which SDKs does VxCloud offer?",
    "How do I install the Python SDK?",
    "Can I run VxCloud on my own hardware?",
]


def _site(url: str) -> str:
    return "salesshift" if "salesshift" in urlparse(url).netloc else "vxcloud"


def write_knowledge_md(ix: DocIndex) -> dict:
    """One .md per site: every section as `## title` + body + source link."""
    buckets: dict[str, list[str]] = {"vxcloud": [], "salesshift": []}
    for c in ix.chunks:
        body = c.text.strip()
        if not body:
            continue
        buckets[_site(c.url)].append(f"## {c.title}\n\n{body}\n\nSource: {c.source_url}\n")
    counts = {}
    titles = {"vxcloud": "VxCloud platform & DevOps documentation",
              "salesshift": "SalesShift sales & marketing platform documentation"}
    for site, parts in buckets.items():
        path = OUT_DIR / f"{site}_knowledge.md"
        path.write_text(f"# {titles[site]}\n\n" + "\n".join(parts), encoding="utf-8")
        counts[path.name] = len(parts)
    return counts


def write_llms(client) -> dict:
    out = {}
    for url, name in [(VXCLOUD_LLMS, "vxcloud_llms.md"), (SALESSHIFT_LLMS, "salesshift_llms.md")]:
        try:
            r = client.get(url, timeout=20, follow_redirects=True)
            if r.status_code == 200 and r.text.strip():
                (OUT_DIR / name).write_text(r.text, encoding="utf-8")
                out[name] = len(r.text)
        except Exception as e:  # noqa: BLE001
            print(f"  warn: could not fetch {url}: {e}")
    return out


def write_vxnode() -> dict:
    if not VXNODE_README.exists():
        return {}
    text = VXNODE_README.read_text(encoding="utf-8", errors="replace")
    # Drop the proprietary-licence preamble; keep from the DevOps runbook onward.
    marker = text.find("# 🚀")
    if marker == -1:
        marker = text.find("## TL;DR")
    body = text[marker:] if marker != -1 else text
    (OUT_DIR / "vxnode_runbook.md").write_text(
        "# vxnode — tenant node DevOps runbook\n\n" + body, encoding="utf-8")
    return {"vxnode_runbook.md": len(body)}


def write_faq(ix: DocIndex) -> dict:
    records = []
    refused = []
    for q in FAQ_QUESTIONS:
        out = answer(q, ix, mode="extractive", k=4)
        if not out["grounded"]:
            refused.append(q)
            continue
        src = out["sources"][0]["url"] if out["sources"] else ""
        records.append({
            "question": q,
            "answer": out["answer"].strip(),
            "source": src,
            "product": _site(src) if src else "",
        })
    (OUT_DIR / "customer_service_faq.json").write_text(
        json.dumps(records, ensure_ascii=False, indent=2), encoding="utf-8")
    if refused:
        print(f"  note: {len(refused)} FAQ question(s) not covered by the index yet: {refused}")
    return {"customer_service_faq.json": len(records)}


def main() -> int:
    import httpx
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    ix_path = default_index_path()
    if not ix_path.exists():
        print(f"ERROR: no docs index at {ix_path}. Run `python -m app.services.docs.build` first.")
        return 1
    ix = DocIndex.load(ix_path)
    print(f"index: {len(ix)} chunks from {ix_path}")

    summary: dict = {}
    summary.update(write_knowledge_md(ix))
    with httpx.Client() as client:
        summary.update(write_llms(client))
    summary.update(write_vxnode())
    summary.update(write_faq(ix))

    print(f"\nWrote {len(summary)} files to {OUT_DIR}:")
    for name, n in summary.items():
        unit = "records" if name.endswith(".json") else ("sections" if name.endswith("_knowledge.md") else "chars")
        print(f"  {name:32} {n:>7} {unit}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
